public class Square {
    public static void main(String[] args) {
        int size = 5; // You can change this size to generate a square of a different size
        for (int i = 0; i < size; i++) {
            for (int j = 0; j < size; j++) {
                System.out.print("*");
            }
            System.out.println();
        }
    }
    
}
